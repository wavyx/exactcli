// Generates docs/coverage.md from the catalogue, the typed list descriptors,
// the command descriptions of the built oclif manifest and
// scripts/live-writes.json. Run via `npm run docs:coverage`. Do not hand-edit
// the output.
//
// A typed command names the calls it makes in its description, for example
// "(POST crm/Accounts)". scripts/live-writes.json lists the write calls that
// were verified live on a test administration; add a call there after a live
// check.
import { readFileSync, writeFileSync } from 'node:fs'
import { gunzipSync } from 'node:zlib'
import { fileURLToPath } from 'node:url'

const FAMILIES = ['regular', 'beta', 'current', 'read', 'sync', 'bulk']
const METHODS = ['GET', 'POST', 'PUT', 'DELETE']
const WRITE_METHODS = ['POST', 'PUT', 'DELETE']
/** The families that carry write calls. */
const WRITE_FAMILIES = new Set(['regular', 'beta', 'current'])
const CALL_RE = /\b(GET|POST|PUT|DELETE) ([a-z]+(?:\/[A-Za-z]+)+)/g

/**
 * The path of a call without the version and the division:
 * `/api/v1/beta/{division}/crm/Accounts` is `crm/Accounts`.
 * @param {string} uri
 * @returns {string}
 */
export function callName(uri) {
  return uri.replace(/^\/api\/v1\/(?:beta\/)?(?:\{division\}\/)?/, '')
}

/**
 * Every call a typed command makes: the list descriptors, then each
 * `METHOD service/Resource` that a command description names.
 * @param {{ commands: Record<string, { id: string, description?: string }> }} manifest
 * @param {Record<string, { topic: string, resource: string }>} descriptors
 * @returns {Map<string, string[]>} call -> command names
 */
export function typedCalls(manifest, descriptors) {
  const typed = new Map()
  const add = (call, command) => {
    const list = typed.get(call) ?? []
    if (!list.includes(command)) list.push(command)
    typed.set(call, list)
  }
  for (const d of Object.values(descriptors)) {
    add(`GET ${d.resource}`, `${d.topic} list`)
  }
  for (const c of Object.values(manifest.commands)) {
    for (const [, method, path] of (c.description ?? '').matchAll(CALL_RE)) {
      add(`${method} ${path}`, c.id.replace(/:/g, ' '))
    }
  }
  return typed
}

/**
 * @param {{ resources: Array<{ uri: string, family: string, methods: string[] }> }} catalog
 * @param {Map<string, string[]>} typed
 * @param {string[]} live write calls verified live
 */
export function buildCoverage(catalog, typed, live) {
  const liveSet = new Set(live)
  const counts = new Map()
  const writes = []
  for (const r of catalog.resources) {
    const name = callName(r.uri)
    for (const method of METHODS.filter((m) => r.methods.includes(m))) {
      const call = `${method} ${name}`
      const key = `${r.family} ${method}`
      const row = counts.get(key) ?? { calls: 0, typed: 0, live: 0 }
      row.calls++
      if (typed.has(call)) row.typed++
      if (liveSet.has(call)) row.live++
      counts.set(key, row)
      if (WRITE_FAMILIES.has(r.family) && WRITE_METHODS.includes(method)) {
        writes.push({
          call,
          typed: typed.get(call) ?? [],
          live: liveSet.has(call),
        })
      }
    }
  }
  const summary = []
  for (const family of FAMILIES) {
    for (const method of METHODS) {
      const row = counts.get(`${family} ${method}`)
      if (!row) continue
      summary.push({
        family,
        method,
        calls: row.calls,
        typed: row.typed,
        live: WRITE_METHODS.includes(method) ? row.live : null,
      })
    }
  }
  return { summary, writes }
}

/**
 * @param {ReturnType<typeof buildCoverage>} coverage
 * @param {{ catalogDate: string }} meta
 * @returns {string}
 */
export function renderCoverage({ summary, writes }, { catalogDate }) {
  const lines = [
    '# API coverage',
    '',
    `Generated by \`npm run docs:coverage\` from the catalogue of ${catalogDate}. Do not`,
    'edit this page by hand.',
    '',
    'Every call of the catalogue is reachable through a generic command: `list` and',
    '`get` (GET), `create` (POST), `update` (PUT), `delete` (DELETE), `sync` (sync',
    'feeds), `list --bulk` (bulk feeds) and the raw `api` command. The generic write',
    'commands validate the body against the catalogue. This page shows which calls also',
    'have a typed command, and which write calls were verified live on a test',
    'administration (`scripts/live-writes.json`).',
    '',
    '## Summary',
    '',
    '| Family | Method | Calls | Typed command | Verified live |',
    '| --- | --- | ---: | ---: | ---: |',
    ...summary.map(
      (r) =>
        `| ${r.family} | ${r.method} | ${r.calls} | ${r.typed} | ${r.live ?? '-'} |`,
    ),
    '',
    '## Write calls',
    '',
    '| Call | Typed command | Verified live |',
    '| --- | --- | --- |',
    ...writes.map(
      (w) =>
        `| ${w.call} | ${w.typed.length ? w.typed.map((c) => `\`${c}\``).join(', ') : '-'} | ${w.live ? 'yes' : 'no'} |`,
    ),
    '',
  ]
  return lines.join('\n')
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const catalog = JSON.parse(
    gunzipSync(readFileSync('src/data/catalog.json.gz')).toString(),
  )
  const manifest = JSON.parse(readFileSync('oclif.manifest.json', 'utf8'))
  const { descriptors } = await import('../src/lib/typed/descriptors.js')
  const live = JSON.parse(readFileSync('scripts/live-writes.json', 'utf8'))
  const coverage = buildCoverage(
    catalog,
    typedCalls(manifest, descriptors),
    live,
  )
  writeFileSync(
    'docs/coverage.md',
    renderCoverage(coverage, {
      catalogDate: String(catalog.generatedAt).slice(0, 10),
    }),
  )
  console.log(`Wrote docs/coverage.md - ${coverage.writes.length} write calls`)
}
